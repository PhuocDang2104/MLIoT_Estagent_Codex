(() => {
  const preferenceKey = 'estagent-language';
  function readPreference(fallback = 'en') {
    try { return localStorage.getItem(preferenceKey) === 'vi' ? 'vi' : 'en'; }
    catch { return fallback; /* Storage may be disabled. */ }
  }
  let language = readPreference();
  const entries = [];
  document.querySelectorAll('[data-vi]').forEach(el => entries.push({ set: value => { el.textContent = value; }, en: el.textContent, vi: el.dataset.vi }));
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const node = walker.currentNode;
    if (node.parentElement.closest('[data-vi],script,style')) continue;
    const text = node.textContent.trim();
    if (landingTranslations[text]) entries.push({ set: value => { node.textContent = value; }, en: node.textContent, vi: node.textContent.replace(text, landingTranslations[text]) });
  }
  for (const [attribute, data] of [['aria-label','ariaVi'],['placeholder','placeholderVi'],['alt','altVi'],['content','contentVi']]) {
    document.querySelectorAll(`[data-${data.replace(/[A-Z]/g, c => '-'+c.toLowerCase())}]`).forEach(el => entries.push({ set: value => el.setAttribute(attribute, value), en: el.getAttribute(attribute), vi: el.dataset[data] }));
  }
  window.estagentI18n = { get language() { return language; }, t: (en, vi) => language === 'vi' ? vi : en };
  function apply(next, persist = false) {
    language = next;
    document.documentElement.lang = language;
    entries.forEach(entry => entry.set(entry[language]));
    document.querySelectorAll('[data-lang]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.lang === language)));
    document.title = document.body.dataset.page === 'creator' ? window.estagentI18n.t('Create a tour — Estagent','Tạo tour — Estagent') : document.body.dataset.page === 'viewer' ? window.estagentI18n.t('View tours — Estagent','Xem tour — Estagent') : document.body.classList.contains('workspace') ? window.estagentI18n.t('Property workspace — Estagent', 'Thông tin căn hộ — Estagent') : window.estagentI18n.t('Estagent — Don’t just view. Explore.', 'Estagent — Không chỉ xem. Hãy khám phá.');
    if (persist) {
      try { localStorage.setItem(preferenceKey, language); } catch { /* Optional preference storage. */ }
    }
    document.dispatchEvent(new Event('languagechange'));
  }
  function syncPreference() {
    const saved = readPreference(language);
    // Do not reset draft notices or rerender user input if nothing changed.
    if (saved !== language) apply(saved);
  }
  document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click', () => apply(button.dataset.lang, true)));
  // A page restored from BFCache does not rerun initialization. Other tabs also
  // need to reflect the shared preference without writing it back in a loop.
  window.addEventListener('pageshow', syncPreference);
  window.addEventListener('storage', event => {
    if (event.key === preferenceKey || event.key === null) syncPreference();
  });
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState === 'visible') syncPreference();
  });
  apply(language);
})();
