async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const check = (condition, label) => { if (!condition) throw new Error(label); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:4173/web/');
  await page.getByRole('link', { name: 'Trải nghiệm ngay', exact: true }).first().click();
  check(page.url().endsWith('experience.html'), 'CTA must open workspace');
  check(await page.locator('input[type=password]').count() === 0, 'No login');
  await page.locator('#file-input').setInputFiles('web/assets/hero.jpg');
  await page.getByText('Đã thêm 1 ảnh.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Xem hero.jpg', exact: true }).click();
  check(await page.locator('dialog').evaluate(el => el.open), 'Preview opens');
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'web/evidence/workspace.png', fullPage: true });
  await page.getByRole('button', { name: 'Xóa hero.jpg', exact: true }).click();
  check(await page.locator('#file-count').textContent() === '0 ảnh', 'Remove photo');
  await page.locator('#file-input').setInputFiles('web/evidence/invalid.png');
  await page.getByText('Đã thêm 0 ảnh. Bỏ qua 1 tệp không hợp lệ hoặc vượt giới hạn.', { exact: true }).waitFor();
  await page.locator('#file-input').setInputFiles('web/assets/hero.jpg');
  await page.getByText('Đã thêm 1 ảnh.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Xóa bộ ảnh', exact: true }).click();
  check(await page.locator('#file-count').textContent() === '0 ảnh', 'Clear photos');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('http://127.0.0.1:4173/web/');
  await page.screenshot({ path: 'web/evidence/mobile.png', fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow');
  await page.getByRole('button', { name: 'Mở menu', exact: true }).click();
  check(await page.locator('#nav-links').isVisible(), 'Mobile menu opens');
  await page.locator('#nav-links').getByRole('link', { name: 'Tính năng', exact: true }).click();
  check(await page.locator('.menu-toggle').getAttribute('aria-expanded') === 'false', 'Menu closes after navigation');
  await page.goto('http://127.0.0.1:4173/web/experience.html');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Workspace mobile overflow');
  await page.screenshot({ path: 'web/evidence/workspace-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 320, height: 740 });
  await page.goto('http://127.0.0.1:4173/web/');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '320px overflow');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('http://127.0.0.1:4173/web/');
  await page.screenshot({ path: 'web/evidence/desktop.png', fullPage: true });
  check(errors.length === 0, `Browser errors: ${errors.join('; ')}`);
  return 'PASS: CTA without login; upload, preview, remove, clear; invalid file; mobile menu; 320/390px overflow; no browser errors.';
}
