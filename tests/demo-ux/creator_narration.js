async page => {
  const base='__BASE_URL__',errors=[];const check=(ok,text)=>{if(!ok)throw Error(text);};
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>r.request().url().startsWith(base+'/')?r.continue():r.abort());
  await page.goto(base+'/qa/narration');
  await page.getByLabel('Approved script',{exact:true}).fill('Welcome to this synthetic test tour.');
  check(await page.getByRole('button',{name:'Generate narration',exact:true}).isDisabled(),'Generation bypasses approval');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Generate narration',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.narration-panel audio').readyState>=2);
  await page.locator('.narration-panel audio').evaluate(a=>a.play());
  await page.waitForFunction(()=>document.querySelector('.narration-panel audio').currentTime>.1);
  await page.getByRole('button',{name:'Attach to draft',exact:true}).click();
  await page.waitForFunction(()=>window.doc.revision===2);
  await page.evaluate(()=>{window.estagentI18n={t:(en,vi)=>vi};document.dispatchEvent(new Event('languagechange'));});
  check(await page.getByRole('button',{name:'Tạo lời giới thiệu',exact:true}).count()===1,'Vietnamese labels not localized');
  check((await page.getByLabel('Lời giới thiệu đã duyệt',{exact:true}).inputValue()).includes('Welcome'),'UI locale translated supplied script');
  await page.getByLabel('Ngôn ngữ lời đọc',{exact:true}).selectOption('vi');
  await page.getByLabel('Lời giới thiệu đã duyệt',{exact:true}).fill('Chào mừng đến với tour kiểm thử.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Tạo lời giới thiệu',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.narration-panel audio').readyState>=2);
  await page.getByRole('button',{name:'Gắn vào bản nháp',exact:true}).click();
  await page.waitForFunction(()=>window.doc.revision===3);
  const document=await page.evaluate(()=>window.doc);check(document.audio.narration.length===2,'EN/VI attachment lost');
  await page.goto(base+'/business/create');
  await page.waitForFunction(()=>document.querySelector('#connection')?.textContent==='Photo tour');
  await page.locator('#message').fill('A synthetic property description for narration QA.');
  await page.evaluate(async()=>{const files=new DataTransfer();for(let i=0;i<2;i++){const r=await fetch('/qa/image/'+i);files.items.add(new File([await r.blob()],'Synthetic '+i+'.png',{type:'image/png'}));}const input=document.querySelector('#photos');input.files=files.files;input.dispatchEvent(new Event('change',{bubbles:true}));});
  await page.locator('#send').click();
  await page.locator('#narration-panel .narration-panel').waitFor();
  await page.getByLabel('Approved script',{exact:true}).fill('This is a synthetic narration in the full Creator UI.');
  await page.getByLabel('Narration language',{exact:true}).selectOption('vi');
  await page.locator('.narration-panel input[type=checkbox]').check();
  await page.getByRole('button',{name:'Generate narration',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.narration-panel audio').readyState>=2);
  await page.getByRole('button',{name:'Attach to draft',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.narration-panel [role=status]')?.textContent.includes('Narration attached'));
  check(await page.locator('#audio-attachments .attached-audio').count()===1,'Creator callback lost attached narration');
  check(await page.locator('#publish').isDisabled(),'Narration attach bypassed publish review');
  check(!errors.length,'JS errors '+errors.join('; '));
  return {pass:true,approvalRequired:true,realFixtureWavPlayback:true,attachedLanguages:['en','vi'],localizedUI:true,scriptNotTranslated:true,fullCreatorAttachCallback:true,errors};
}
