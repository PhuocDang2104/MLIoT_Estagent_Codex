async page => {
  const base='__BASE_URL__';
  await page.route('**/*',route=>route.request().url().startsWith(base+'/')?route.continue():route.abort());
  await page.goto(base+'/qa/narration');
  await page.getByLabel('Approved script / Lời giới thiệu').fill('Welcome to the tour.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Generate voice / Sinh giọng',exact:true}).click();
  await page.getByRole('button',{name:'Attach to draft / Gắn vào bản nháp',exact:true}).waitFor({state:'visible'});
  await page.waitForFunction(()=>!document.querySelector('.narration-panel audio').src.endsWith('/qa/narration')&&document.querySelector('.narration-panel audio').readyState>=2);
  await page.locator('.narration-panel audio').evaluate(a=>a.play());
  await page.waitForFunction(()=>document.querySelector('.narration-panel audio').currentTime>0.1);
  await page.getByRole('button',{name:'Attach to draft / Gắn vào bản nháp',exact:true}).click();
  await page.waitForFunction(()=>window.doc.revision===2);
  await page.getByLabel('Audio language / Ngôn ngữ lời').selectOption('vi');
  await page.getByLabel('Approved script / Lời giới thiệu').fill('Chào mừng bạn đến với tour.');
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Generate voice / Sinh giọng',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.narration-panel audio').readyState>=2);
  await page.getByRole('button',{name:'Attach to draft / Gắn vào bản nháp',exact:true}).click();
  await page.waitForFunction(()=>window.doc.revision===3);
  const snapshot=await page.evaluate(async()=>{const d=window.doc;await window.api(`/drafts/${d.id}/review`,{method:'POST',body:{revision:d.revision}});return window.api(`/drafts/${d.id}/publish`,{method:'POST',body:{revision:d.revision}});});
  if(snapshot.audio.narration.length!==2)throw Error('Bilingual snapshot missing');
  await page.goto(base+'/viewer.html?tour='+snapshot.id);
  await page.locator('#viewer-audio summary').click();
  await page.locator('#audio-language').selectOption('vi');
  await page.locator('#play').click();
  await page.waitForFunction(()=>document.querySelector('#narration-track').currentTime>0);
  const vi=await page.locator('#narration-track').getAttribute('src');
  if(!vi.includes(snapshot.audio.narration.find(n=>n.locale==='vi').track.asset_id))throw Error('Wrong VI asset');
  await page.locator('#viewer-chat summary').click();
  await page.waitForFunction(()=>document.querySelector('#narration-track').paused);
  await page.locator('#viewer-audio summary').click();
  await page.locator('#audio-language').selectOption('en');
  const en=await page.locator('#narration-track').getAttribute('src');
  if(en===vi)throw Error('Language failed');
  await page.locator('#next').click();
  if(!await page.locator('#narration-enabled').isDisabled())throw Error('Missing track not shown');
  await page.screenshot({path:'tests/narration/evidence/viewer.png',fullPage:true});
  return {pass:true,component:'generate-preview-attach EN/VI',media:'actual playable fixture PCM WAV',viewer:'language/missing-track/chat-pause',snapshot:snapshot.id};
}
