def source(client, music_seconds=6):
    client.get('/api/tours/session');assets=[]
    for number,color in [(1,'#526e75'),(2,'#956d47')]:
        image=Image.new('RGB',(1280,720),color);draw=ImageDraw.Draw(image)
        for x in range(80,1280,150):draw.rectangle((x,60,x+70,590),outline='white',width=8)
        out=io.BytesIO();image.save(out,format='PNG')
        response=client.post('/api/tours/assets',headers=HEAD,content=out.getvalue());assert response.status_code==200,response.text
        assets.append(response.json()['id'])
    draft=client.post('/api/tours/drafts',headers=HEAD,json={'asset_ids':assets,'locale':'en','title':'Synthetic home tour','request_id':'export-source-1'}).json()
    def audio(frequency,seconds):
        out=io.BytesIO();samples=array.array('h',(int(3000*math.sin(i*frequency*2*math.pi/16000)) for i in range(int(seconds*16000))))
        if sys.byteorder!='little':samples.byteswap()
        with wave.open(out,'wb') as wav:wav.setnchannels(1);wav.setsampwidth(2);wav.setframerate(16000);wav.writeframes(samples.tobytes())
        from urllib.parse import quote
        meta={'source_label':'Synthetic test tone','rights':'owned','rights_note':'Generated by the test; no human voice or licensed music.'}
        response=client.post('/api/tours/audio-assets',headers=HEAD|{'X-Audio-Metadata':quote(json.dumps(meta))},content=out.getvalue());assert response.status_code==200,response.text
        return response.json()
    music=audio(220,music_seconds);voices=[audio(440,1),audio(660,1)]
    data={'revision':1,'music_asset_id':music['asset_id'],'narration':[{'scene_id':s['id'],'locale':'en','asset_id':v['asset_id'],'transcript':f'Synthetic checkpoint {i+1}. Test tone, not speech.'} for i,(s,v) in enumerate(zip(draft['scenes'],voices))]}
    attached=client.put(f'/api/tours/drafts/{draft["id"]}/audio',headers=HEAD,json=data);assert attached.status_code==200,attached.text
    route=f'/api/tours/drafts/{draft["id"]}'
    assert client.post(route+'/review',headers=HEAD,json={'revision':2}).status_code==200
    published=client.post(route+'/publish',headers=HEAD,json={'revision':2});assert published.status_code==200,published.text
    return published.json()


def test_real_exports_and_boundaries(tmp_path):
    # QA_OUTPUT_DIR is operator supplied private scratch, never tracked media.
    output_root=Path(os.environ.get('QA_OUTPUT_DIR',str(tmp_path/'output')));output_root.mkdir(parents=True,exist_ok=True)
    root=output_root/'state';root.mkdir(exist_ok=True)
    app=make_app(root);records=[]
    with TestClient(app) as client:
        assert client.get('/api/tours/exports/sources').status_code==401
        snapshot=source(client)
        snapshot_hash=hashlib.sha256(json.dumps(snapshot,sort_keys=True).encode()).hexdigest()
        assert client.get('/export.html?name=/etc/passwd').status_code==200
        assert 'root:' not in client.get('/export.html?name=/etc/passwd').text
        for aspect in ['portrait','landscape']:
            preview=client.get(f'/api/tours/exports/preview/{snapshot["id"]}?aspect={aspect}');assert preview.status_code==200
            assert preview.json()['audio_status']=='complete' and preview.json()['duration']==6
            body={'tour_id':snapshot['id'],'aspect':aspect,'request_id':'export-'+aspect}
            response=client.post('/api/tours/exports',json=body,headers=HEAD);assert response.status_code==200,response.text
            job=response.json();app.state.wait_video_exports()
            done=client.get('/api/tours/exports/'+job['id']).json();assert done['state']=='ready',done
            assert client.post('/api/tours/exports',json=body,headers=HEAD).json()['id']==job['id']
            assert client.post('/api/tours/exports',json=body|{'aspect':'landscape' if aspect=='portrait' else 'portrait'},headers=HEAD).status_code==409
            response=client.get(done['download']);assert response.status_code==200 and response.headers['content-type']=='video/mp4'
            (output_root/(aspect+'.mp4')).write_bytes(response.content)
            assert client.get(done['download'],headers={'Range':'bytes=0-99'}).status_code==206
            probe=json.loads(run_process(['ffprobe','-v','error','-show_streams','-show_format','-of','json',str(output_root/(aspect+'.mp4'))],output_root,15,output_root/(aspect+'-probe.json')))
            records.append({'aspect':aspect,'job':job['id'],'streams':[{k:s.get(k) for k in ['codec_type','codec_name','width','height','duration']} for s in probe['streams']],'duration':probe['format']['duration']})
        current=client.get('/api/tours/published/'+snapshot['id']).json()
        assert hashlib.sha256(json.dumps(current,sort_keys=True).encode()).hexdigest()==snapshot_hash
        owner_cookie=client.cookies.get('estagent_tours')
        client.cookies.clear();assert client.get(done['download']).status_code==401
        client.get('/api/tours/session');assert client.get(done['download']).status_code==404
        assert client.get('/api/tours/exports/preview/'+snapshot['id']).status_code==404
        assert client.post('/api/tours/exports',headers=HEAD,json={'tour_id':snapshot['id'],'aspect':'portrait','request_id':'other-owner'}).status_code==404
    restarted=make_app(root)
    with TestClient(restarted) as client:
        client.cookies.set('estagent_tours',owner_cookie,path='/api/tours/')
        assert client.get(done['download']).status_code==200
        # Simulate persisted crash state, not a fake successful render.
        with sqlite3.connect(root/'tours/tours.sqlite') as conn:
            conn.execute("UPDATE video_exports SET state='rendering' WHERE id=?",(job['id'],))
    interrupted=make_app(root)
    with TestClient(interrupted) as client:
        client.cookies.set('estagent_tours',owner_cookie,path='/api/tours/')
        result=client.get('/api/tours/exports/'+job['id']).json();assert result['state']=='error' and result['stage']=='interrupted'
    EVIDENCE.mkdir(exist_ok=True)
    (EVIDENCE/'exports.json').write_text(json.dumps({'actual_render':True,'synthetic':True,'snapshot_immutable':True,'owner_isolation':True,'range':True,'idempotent':True,'restart_ready':True,'interrupted_state':True,'outputs':records},indent=2)+'\n')
    # Private runtime fixture for browser QA, never stage this file.
    (output_root/'browser-private.json').write_text(json.dumps({'cookie':owner_cookie,'tour_id':snapshot['id'],'job_id':records[0]['job'],'root':str(root)}))


def test_actual_timeout(tmp_path):
    started=time.monotonic()
    with pytest.raises(RuntimeError,match='timed out'):
        run_process([sys.executable,'-c',"import subprocess,sys,time; subprocess.Popen([sys.executable,'-c','import time; time.sleep(10)']); time.sleep(10)"],tmp_path,.2,tmp_path/'timeout.log')
    assert time.monotonic()-started<5  # Both children must close the inherited output pipe.


def test_real_source_error_and_persisted_global_allowance(tmp_path):
    app=make_app(tmp_path)
    with TestClient(app) as client:
        snapshot=source(client)
        draft_id=client.get('/api/tours/session').json()['drafts'][0]['id']
        draft=client.get('/api/tours/drafts/'+draft_id).json()
        edits={k:draft[k] for k in ['revision','title','locale','start_scene_id']}
        edits['title']='UNPUBLISHED EDIT';edits['locale']='vi'
        edits['scenes']=[{k:v for k,v in s.items() if k not in {'image_url','thumbnail_url'}} for s in draft['scenes']]
        assert client.put('/api/tours/drafts/'+draft_id,headers=HEAD,json=edits).status_code==200
        preview=client.get('/api/tours/exports/preview/'+snapshot['id']).json()
        assert preview['title']=='Synthetic home tour' and preview['locale']=='en' and preview['audio_status']=='complete'
        (tmp_path/'tours/assets'/f'{snapshot["scenes"][0]["asset_id"]}.jpg').unlink()
        body={'tour_id':snapshot['id'],'aspect':'portrait','request_id':'real-source-error'}
        response=client.post('/api/tours/exports',headers=HEAD,json=body);assert response.status_code==200
        job=response.json();app.state.wait_video_exports()
        result=client.get('/api/tours/exports/'+job['id']).json()
