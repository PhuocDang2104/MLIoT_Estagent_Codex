        assert client.get('/api/tours/exports/'+job['id']+'/download').status_code==409
        assert client.post('/api/tours/exports',headers=HEAD,json=body).json()['id']==job['id']
        # Seed bounded-queue/history metadata, not mock successful processes or MP4s.
        with sqlite3.connect(tmp_path/'tours/tours.sqlite') as conn:
            for i in range(2):
                conn.execute("INSERT INTO video_exports SELECT ?,?, ?,body,snapshot,edit,'queued','queued',NULL,created,NULL FROM video_exports WHERE id=?",(f'{i:032x}','prior-owner',f'queue-request-{i}',job['id']))
